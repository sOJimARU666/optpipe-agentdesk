#!/usr/bin/env python3
"""Regenerate src/optpipe/models/schema_v1.py from Doodle's session.schema.json (read-only).

Usage: .venv/bin/python scripts/gen_models.py [SPEC_DIR]
The schema's sha256 is embedded so tests can detect drift when Doodle changes the schema.
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("OPTIONS_SPEC_DIR", "/workspace/trading/spec"))
schema = spec / "session.schema.json"
digest = hashlib.sha256(schema.read_bytes()).hexdigest()
with tempfile.TemporaryDirectory() as td:
    out = Path(td) / "m.py"
    subprocess.run([str(Path(sys.executable).parent / "datamodel-codegen"), "--input", str(schema),
                    "--input-file-type", "jsonschema", "--output", str(out),
                    "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.11",
                    "--use-standard-collections", "--use-union-operator", "--field-constraints",
                    "--use-title-as-name", "--disable-timestamp", "--set-default-enum-member"], check=True, capture_output=True)
    code = out.read_text()
# Keep URLs verbatim (AnyUrl normalises them, which would break lossless round-trips).
code = code.replace("AnyUrl, ", "").replace("url: AnyUrl", "url: str")
code = re.sub(r"^# generated by datamodel-codegen:.*?\n\n", "", code, flags=re.S)
doc = ('"""GENERATED from Doodle\'s session.schema.json - do not edit by hand.\n\n'
       'Regenerate: .venv/bin/python scripts/gen_models.py\n"""\n')
consts = f'\nSCHEMA_SHA256 = "{digest}"\nSCHEMA_SOURCE = "{schema}"\n'
code = code.replace("from __future__ import annotations\n", doc + "from __future__ import annotations\n" + consts, 1)
# JSON "number" -> int | float so 472 stays 472 and 340.0 stays 340.0 (lossless round-trip).
import re as _re
code = _re.sub(r"\bfloat\b", "Number", code)
code = code.replace("from pydantic import", "Number = int | float  # JSON Schema 'number', kept lossless\n\nfrom pydantic import", 1)
# Timestamps: validated as offset-aware ISO-8601 but kept as the original string (lossless; "+00:00" stays "+00:00").
code = code.replace("from pydantic import AwareDatetime, ", "from pydantic import ")
code = code.replace("from pydantic import", (
    "from datetime import datetime as _dt\nfrom typing import Annotated\nfrom pydantic import AfterValidator\n\n\n"
    "def _aware(v: str) -> str:\n"
    "    if _dt.fromisoformat(v).tzinfo is None:\n"
    "        raise ValueError(f'timestamp needs an explicit UTC offset: {v}')\n"
    "    return v\n\n\n"
    "AwareTs = Annotated[str, AfterValidator(_aware)]  # offset-aware ISO-8601, stored verbatim\n\n"
    "from pydantic import"), 1)
code = code.replace("AwareDatetime", "AwareTs")
code += "\n\nSessionRecordV1 = PaperUSOptionsTradingSessionRecord\n"
(ROOT / "src/optpipe/models/schema_v1.py").write_text(code)
print(f"wrote schema_v1.py from {schema} sha256={digest[:12]}")
