#!/usr/bin/env python3
"""Regenerate the pydantic models from the session schemas (both read-only inputs).

  models/schema_v1.py    <- Doodle's frozen v1.0.0 schema: <spec_dir>/_v1_backup/session.schema.json
                            (<spec_dir>/session.schema.json while the spec has no _v1_backup)  (SessionRecordV1)
  models/schema_spec.py  <- Doodle's live <spec_dir>/session.schema.json (v1.1 merged 2026-10-29)  (SessionRecordSpec)
  models/schema_v1_1.py  <- proposal  spec_patches/v1.1/session.schema.json (SessionRecordV11)

Usage: .venv/bin/python scripts/gen_models.py [--check] [--spec-dir DIR]
--check regenerates in memory and exits 1 if a committed model file differs (CI drift guard).
The schema sha256 is embedded so tests can also detect drift without the generator installed.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "src/optpipe/models"


def generate(schema: Path, label: str, alias: str, source_str: str) -> str:
    digest = hashlib.sha256(schema.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / "m.py"
        subprocess.run([str(Path(sys.executable).parent / "datamodel-codegen"), "--input", str(schema),
                        "--input-file-type", "jsonschema", "--output", str(out),
                        "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.11",
                        "--use-standard-collections", "--use-union-operator", "--field-constraints",
                        "--use-title-as-name", "--disable-timestamp", "--set-default-enum-member"],
                       check=True, capture_output=True)
        code = out.read_text()
    # Keep URLs verbatim (AnyUrl normalises them, which would break lossless round-trips).
    code = code.replace("AnyUrl, ", "").replace("url: AnyUrl", "url: str")
    code = re.sub(r"^# generated by datamodel-codegen:.*?\n\n", "", code, flags=re.S)
    doc = (f'"""GENERATED from {label} - do not edit by hand.\n\n'
           'Regenerate: .venv/bin/python scripts/gen_models.py\n"""\n')
    consts = f'\nSCHEMA_SHA256 = "{digest}"\nSCHEMA_SOURCE = "{source_str}"\n'
    code = code.replace("from __future__ import annotations\n", doc + "from __future__ import annotations\n" + consts, 1)
    # JSON "number" -> int | float so 472 stays 472 and 340.0 stays 340.0 (lossless round-trip).
    code = re.sub(r"\bfloat\b", "Number", code)
    code = code.replace("from pydantic import", "Number = int | float  # JSON Schema 'number', kept lossless\n\nfrom pydantic import", 1)
    # Timestamps: validated as offset-aware ISO-8601 but kept as the original string (lossless).
    code = code.replace("from pydantic import AwareDatetime, ", "from pydantic import ")
    code = code.replace("from pydantic import", (
        "from datetime import datetime as _dt\nfrom typing import Annotated\nfrom pydantic import AfterValidator\n\n\n"
        "def _aware(v: str) -> str:\n"
        "    if _dt.fromisoformat(v).tzinfo is None:\n"
        "        raise ValueError(f'timestamp needs an explicit UTC offset: {v}')\n"
        "    return v\n\n\n"
        "AwareTs = Annotated[str, AfterValidator(_aware)]  # offset-aware ISO-8601, stored verbatim\n\n"
        "from pydantic import"), 1)
    code = code.replace("AwareDatetime", "AwareTs")
    code += f"\n\n{alias} = PaperUSOptionsTradingSessionRecord\n"
    return code


def v1_base(spec_dir: Path) -> Path:
    """Folder holding Doodle's v1.0.0 files: the frozen _v1_backup once v1.1 is merged, else the spec itself."""
    b = spec_dir / "_v1_backup"
    return b if (b / "session.schema.json").exists() else spec_dir


def targets(spec_dir: Path):
    v1 = v1_base(spec_dir) / "session.schema.json"
    yield MODELS / "schema_v1.py", generate(v1, "Doodle's v1.0.0 session.schema.json", "SessionRecordV1",
                                              "<spec>/" + str(v1.relative_to(spec_dir)))   # live folder or pinned spec/
    live = spec_dir / "session.schema.json"
    yield MODELS / "schema_spec.py", generate(live, "Doodle's live session.schema.json", "SessionRecordSpec",
                                                  "<spec>/session.schema.json")
    v11 = ROOT / "spec_patches/v1.1/session.schema.json"
    if v11.exists():
        yield MODELS / "schema_v1_1.py", generate(v11, "the v1.1 PROPOSAL spec_patches/v1.1/session.schema.json",
                                                  "SessionRecordV11", "spec_patches/v1.1/session.schema.json")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if committed models differ from a fresh generation")
    ap.add_argument("--spec-dir", default=os.environ.get("OPTIONS_SPEC_DIR", "/workspace/trading/spec"))
    ap.add_argument("legacy_spec_dir", nargs="?")
    a = ap.parse_args(argv)
    spec_dir = Path(a.legacy_spec_dir or a.spec_dir)
    stale = []
    for path, code in targets(spec_dir):
        if a.check:
            if not path.exists() or path.read_text() != code:
                stale.append(path.name)
        else:
            path.write_text(code)
            print(f"wrote {path.relative_to(ROOT)}")
    if a.check:
        print("models up to date" if not stale else f"models STALE (run scripts/gen_models.py): {stale}")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
