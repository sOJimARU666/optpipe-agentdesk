"""Test helpers (spec 1.1.3, current example 1.1.4): a valid 1.1.4 record (1.1.3 checks) with a FLAG review, an approval and an open paper position,
built from session.example.json in memory. PAPER ONLY: fills are simulated; nothing here places an order.
Never written to disk; session.example.json stays generated by build_example.py."""
from __future__ import annotations

import copy
import json
from pathlib import Path

import risk_reference as rr

SPEC = Path(__file__).resolve().parent
TK = "tkt-jpm-bcs-340-350"
FLAGS = ["R08_MACRO_EVENTS", "R10_IV_VS_HISTORY", "R11_CONCENTRATION"]   # soft UNKNOWN, soft UNKNOWN, FLAG


def example() -> dict:
    return json.loads((SPEC / "session.example.json").read_text())


def tp(ny: str) -> dict:
    """TsPair from an aware NY ISO string."""
    return rr.tspair(rr.ts(ny))


def at(hhmm: str) -> dict:
    return tp(f"2026-10-13T{hhmm}:00-04:00")


def flag_review(sess: dict, review_id: str = "rv-flag", evaluated: str = "12:21") -> dict:
    """rv-postopen with its VETO rules forced to PASS and R11 forced to FLAG -> overall FLAG via rr.overall."""
    rv = copy.deepcopy(next(r for r in sess["risk_reviews"] if r["review_id"] == "rv-postopen"))
    rv["review_id"], rv["evaluated_at"] = review_id, at(evaluated)
    for r in rv["results"]:
        if r["result"] == "VETO":
            r["result"] = "PASS"
        if r["rule_id"] == "R11_CONCENTRATION":
            r["result"] = "FLAG"
    ov = rr.overall(rv["results"])
    rv["overall"] = {**ov, "summary": "test fixture"}
    assert ov["verdict"] == "FLAG" and ov["flag_rule_ids"] == FLAGS, ov
    return rv


def approval(sess: dict, review_id: str = "rv-flag", **kw) -> dict:
    t = next(x for x in sess["tickets"] if x["ticket_id"] == TK)
    a = {"approval_id": "ap-1", "ticket_id": TK, "review_id": review_id,
         "approver": {"name": "Eugene Ward", "channel": "web_ui", "evidence": "test fixture"},
         "approved_at": at("12:25"), "expires_at": at("16:00"),
         "legs": copy.deepcopy(t["legs"]), "quantity": t["quantity"], "limit_price": copy.deepcopy(t["limit_price"]),
         "acknowledged_flags": list(FLAGS), "status": "active"}
    a.update(kw)
    return a


def fill(fill_id, leg_id, contract_id, action, price, when="12:30", qty=1) -> dict:
    return {"fill_id": fill_id, "leg_id": leg_id, "contract_id": contract_id, "action": action, "qty": qty, "price": price,
            "filled_at": at(when), "quote_source_id": "src-nasdaq-jpm-chain-1216", "simulated": True}


def position(**kw) -> dict:
    """debit 4.00 - 0.95 = 3.05 <= approved limit 3.10"""
    p = {"position_id": "pos-1", "ticket_id": TK, "approval_id": "ap-1", "status": "open",
         "fills": [fill("f-1", "leg-1", "JPM261030C00340000", "buy_to_open", 4.00),
                   fill("f-2", "leg-2", "JPM261030C00350000", "sell_to_open", 0.95)],
         "marks": []}
    p.update(kw)
    return p


def approved_record(with_position: bool = True) -> dict:
    """valid 1.1.4 record (same checks as 1.1.3): FLAG review rv-flag (latest), approval ap-1 acknowledging every flag, open position pos-1.
    The idea is moved to approved_pending -> approved so the record tells one consistent story."""
    s = example()
    assert s["schema_version"] == "1.1.4"
    s["risk_reviews"].append(flag_review(s))
    s["approvals"].append(approval(s))
    if with_position:
        s["paper_positions"].append(position())
    idea = next(i for i in s["idea_log"] if i["ticket_id"] == TK)
    for st, hhmm, actor in (("approved_pending", "12:21", "decision_maker"), ("approved", "12:25", "user")):
        idea["history"].append({"status": st, "at": at(hhmm), "actor": actor, "reason": "test fixture"})
    idea["current_status"] = "approved"
    return s
